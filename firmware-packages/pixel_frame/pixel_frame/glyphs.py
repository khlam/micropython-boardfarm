def glyph(char: str) -> tuple:
    """Return precomputed column bytes and metrics for one character."""
    if "a" <= char <= "z":
        char = char.upper()
    return _GLYPHS.get(char, _GLYPHS["?"])


def _compile_glyphs(patterns: dict) -> dict:
    """Convert row-string glyphs into column bytes and metrics once."""
    glyphs = {}
    for char, rows in patterns.items():
        width = max(len(row) for row in rows)
        cols = bytearray(width)
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "1":
                    cols[x] |= 1 << y
        glyphs[char] = (bytes(cols), width)
    return glyphs


