def glyph(ch: str) -> bytes:
    """Return the 5-byte column bitmap for ``ch``.

    Characters outside the printable ASCII range render as a blank cell, so
    callers never have to pre-filter strings.
    """
    code = ord(ch)
    if code < FIRST or code > LAST:
        return _BLANK
    offset = (code - FIRST) * WIDTH
    return _FONT[offset : offset + WIDTH]
